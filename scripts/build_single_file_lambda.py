def _name_of(node):
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return {node.name}
    if isinstance(node, ast.Assign):
        return {t.id for t in node.targets if isinstance(t, ast.Name)}
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return {node.target.id}
    return set()


def _segment(lines, node):
    """Whole top-level statement INCLUDING its decorators (get_source_segment drops them)."""
    start = min([d.lineno for d in getattr(node, "decorator_list", [])] + [node.lineno])
    return "\n".join(lines[start - 1:node.end_lineno])


def _imports_block(plain, from_imports):
    lines = sorted(f"import {name}" for name in plain)
    lines += [f"from {module} import {', '.join(sorted(names))}" for module, names in sorted(from_imports.items())]
    return "\n".join(lines)


def generate():
    plain, from_imports, blocks, defined = set(), {}, [], {}
    for rel, keep in SOURCES:
        source = (ROOT / rel).read_text(encoding="utf-8")
        lines = source.splitlines()
        tree = ast.parse(source)
        parts = []
        for index, node in enumerate(tree.body):
            if index == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
                continue                                   # module docstring
            if isinstance(node, ast.ImportFrom):
                if not str(node.module).startswith(PROJECT_PACKAGES):
                    from_imports.setdefault(node.module, set()).update(a.name for a in node.names)
                continue
            if isinstance(node, ast.Import):
                plain.update(a.name for a in node.names)
                continue
            names = _name_of(node)
            if keep is not None and not names & keep:
                continue
            for name in names:
                if name in defined and defined[name] != rel:
                    raise SystemExit(f"Name clash: {name} defined in {defined[name]} and {rel}")
                defined[name] = rel
            simple = isinstance(node, (ast.Assign, ast.AnnAssign))
            text = _segment(lines, node)
            if parts and simple and parts[-1][0]:
                parts[-1] = (True, parts[-1][1] + "\n" + text)    # keep constants together
            else:
                parts.append((simple, text))
        body = "\n\n\n".join(text for _, text in parts)
        blocks.append(f"# {'=' * 70}\n# from {rel}\n# {'=' * 70}\n" + body)
    code = HEADER + _imports_block(plain, from_imports) + "\n\n\n" + "\n\n\n".join(blocks)
    code += "\n"
    compile(code, str(OUT), "exec")
    return code


def main():
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(generate(), encoding="utf-8")
    print(f"Created {OUT.relative_to(ROOT)} ({len(OUT.read_text(encoding='utf-8').splitlines())} lines)")


if __name__ == "__main__":
    main()
