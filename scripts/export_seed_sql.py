"""Write the initial data (DML) of PostgreSQL as a plain SQL file:

    python scripts/export_seed_sql.py            -> database/operations_seed.sql

It contains exactly what scripts/load_to_sql.py loads (same fixed seed, so the
product, seller and user ids match DynamoDB): 29 categories, 12 sellers,
27,068 reviews, sales history and stock alerts. Dates are relative to the day
the file is generated (sales of the last 30 days), like the loader.

Run the file on an EMPTY schema created by operations_db.sql, for example with
psql -f database/operations_seed.sql or pgAdmin's Query Tool.
"""
import sys
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "database" / "operations_seed.sql"
BATCH = 500
COLUMNS = {
    "categories": ("category_id", "parent_id", "name", "slug", "is_active"),
    "sellers": ("seller_id", "user_id", "store_name", "tax_id", "rating", "status", "created_at"),
    "reviews": ("product_id", "buyer_id", "rating", "comment", "created_at"),
    "analytics": ("product_id", "category_id", "seller_id", "quantity_sold", "sale_date"),
    "alerts": ("product_id", "seller_id", "current_stock", "threshold_limit", "alert_status", "updated_at"),
}
ORDER = ("categories", "sellers", "reviews", "analytics", "alerts")     # foreign keys first


def literal(value):
    """Python value -> SQL literal (strings quoted with '' escaping; no user input here)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, datetime):
        return "'" + value.strftime("%Y-%m-%d %H:%M:%S") + "'"
    if isinstance(value, date):
        return "'" + value.isoformat() + "'"
    return "'" + str(value).replace("'", "''") + "'"


def statements(rows):
    """INSERT statements of every table, 500 rows per statement."""
    out = []
    for table in ORDER:
        data = rows[table]
        cols = ", ".join(COLUMNS[table])
        for i in range(0, len(data), BATCH):
            values = ",\n  ".join("(" + ", ".join(literal(v) for v in row) + ")" for row in data[i:i + BATCH])
            out.append(f"INSERT INTO {table} ({cols}) VALUES\n  {values};")
    return out


def render(rows, today=None):
    counts = ", ".join(f"{len(rows[t])} {t}" for t in ORDER)
    head = f"""-- =====================================================================
-- PostgreSQL: INITIAL DATA (DML) of the marketplace
-- =====================================================================
-- Generated by scripts/export_seed_sql.py on {(today or date.today()).isoformat()}.
-- {counts}.
-- Same data (and ids) as scripts/load_to_sql.py and the products/users in DynamoDB.
-- Run it once, on the empty tables created by database/operations_db.sql.
-- =====================================================================

BEGIN;
"""
    tail = """
-- categories use explicit ids: move the SERIAL counter after them
SELECT setval(pg_get_serial_sequence('categories', 'category_id'), (SELECT MAX(category_id) FROM categories));

COMMIT;
"""
    return head + "\n" + "\n\n".join(statements(rows)) + "\n" + tail


def main():
    from scripts.load_to_sql import build_rows
    rows = build_rows(17000)
    OUT.write_text(render(rows), encoding="utf-8")
    size = OUT.stat().st_size / 1_000_000
    print(f"Created {OUT.relative_to(ROOT)} ({size:.1f} MB): " + ", ".join(f"{len(rows[t])} {t}" for t in ORDER))


if __name__ == "__main__":
    main()
