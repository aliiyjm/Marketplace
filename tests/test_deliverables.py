def test_real_lambda_responses_match_the_openapi_schemas(monkeypatch):
    jsonschema = pytest.importorskip("openapi_schema_validator")
    from Implementation.ProductServiceImplementation.ProductServiceImplementation import \
        ProductServiceImplementation
    from scripts.load_to_dynamo import build_payloads
    from Services.ProductService.ProductService import handle_productos
    from tests.fake_dynamo import FakeTable, auth
    monkeypatch.setenv("MARKETPLACE_API_KEY", "k")
    spec = _spec()
    svc = ProductServiceImplementation(FakeTable())
    payload = build_payloads(3)[0]

    def call(method, path, body=None, query=None):
        out = handle_productos({"rawPath": path, "requestContext": {"http": {"method": method}},
                                "headers": auth("k"), "queryStringParameters": query,
                                "body": json.dumps(body) if body is not None else None}, service=svc)
        return out["statusCode"], json.loads(out["body"])

    def schema_of(path, method, status):
        content = spec["paths"][path][method]["responses"][status]
        if "$ref" in content:
            content = spec["components"]["responses"][content["$ref"].rsplit("/", 1)[1]]
        return dict(content["content"]["application/json"]["schema"], components=spec["components"])

    cases = [
        ("post", "/productos/agregar", payload, None, "201"),
        ("get", "/productos/consultar", None, {"product_id": payload["product_id"]}, "200"),
        ("post", "/productos/reservar", {"order_id": "10001", "items": [{"product_id": payload["product_id"], "qty": 1}]}, None, "200"),
        ("post", "/productos/liberar", {"order_id": "10001"}, None, "200"),
        ("post", "/productos/liberar", {"order_id": "99"}, None, "404"),
    ]
    for method, path, body, query, status in cases:
        got_status, got = call(method.upper(), path, body, query)
        assert str(got_status) == status, (path, got)
        resolver = jsonschema.validators.OAS30Validator
        resolver(schema_of(path, method, status)).validate(got)
