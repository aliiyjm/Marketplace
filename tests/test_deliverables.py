# ---------------- DML ----------------
def _sqlite_statements(sql):
    """The PostgreSQL seed without the lines SQLite does not have (BEGIN/COMMIT/setval)."""
    body = "\n".join(line for line in sql.splitlines()
                     if not line.startswith(("BEGIN", "COMMIT", "SELECT setval", "--")))
    return body


def test_operations_seed_file_loads_with_every_foreign_key(tmp_path):
    sql = (DATABASE / "operations_seed.sql").read_text(encoding="utf-8")
    counts = dict((t, int(n)) for n, t in re.findall(r"(\d+) (categories|sellers|reviews|analytics|alerts)",
                                                       sql.splitlines()[4]))
    assert counts["categories"] == 29 and counts["sellers"] == 12 and counts["reviews"] > 27000
    db = sqlite_database(str(tmp_path / "ops.db"), OPERATIONS, "PostgreSQL (seed test)")
    conn = db._connect()
    conn.executescript(_sqlite_statements(sql))
    for table, expected in counts.items():
        assert conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0] == expected
    assert conn.execute("PRAGMA foreign_key_check").fetchall() == []
    conn.close()


def test_seed_generator_matches_the_loader():
    rows = build_rows(300)
    sql = render(rows, today=date(2026, 1, 2))
    assert "Generated by scripts/export_seed_sql.py on 2026-01-02" in sql
    inserts = re.findall(r"^INSERT INTO (\w+)", sql, re.M)
    assert list(dict.fromkeys(inserts)) == [t for t in ORDER if rows[t]]   # parents before children
    assert sql.count("(") >= sum(len(v) for v in rows.values())
    assert "'O''Brien'" in render({**{t: [] for t in ORDER}, "categories": [(1, None, "O'Brien", "ob", True)]})


def test_finance_seed_only_uses_the_stored_procedures():
    sql = (DATABASE / "finance_seed.sql").read_text(encoding="utf-8")
    code = "\n".join(line.split("--", 1)[0] for line in sql.splitlines())
    statements = [s.strip() for s in code.split(";") if s.strip()]
    assert statements and all(s.startswith("CALL ") for s in statements)
    assert not re.search(r"\b(INSERT|UPDATE|DELETE|DROP)\b", code, re.I)
    called = {re.match(r"CALL (\w+)\(", s).group(1) for s in statements}
    assert called <= set(MYSQL_ROUTINES) and called == set(MYSQL_ROUTINES)
    total = Decimal("0")
    for statement in statements:
        if statement.startswith("CALL sp_create_order("):
            lines = json.loads(re.search(r"'(\[.*?\])'", statement, re.S).group(1))
            for line in lines:
                assert re.fullmatch(r"PRD-\d{6}", line["product_id"]) and 1 <= line["quantity"] <= 10
            if "'CASH'" not in statement:                                 # order 90003 is cancelled
                total += sum(Decimal(l["unit_price"]) * l["quantity"] for l in lines)
    assert total == Decimal("2796.00")                                    # the value the file announces


